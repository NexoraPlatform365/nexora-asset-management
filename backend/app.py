@app.get("/api/health")
def health():
    status = {"ok": True, "service": "Nexora API", "mode": "investor-portal", "time": datetime.now(timezone.utc).isoformat(), "database": "postgresql" if USE_POSTGRES else "sqlite"}
    try:
        execute("SELECT 1").fetchone()
        status["database_status"] = "connected"
    except Exception:
        app.logger.exception("Database health check failed")
        return jsonify({"ok": False, "service": "Nexora API", "database_status": "error"}), 503
    return jsonify(status)

@app.get("/api/csrf")
def get_csrf():
    response = jsonify({"csrf_token": csrf_token()})
    response.headers["Cache-Control"] = "no-store"
    return response

@app.post("/api/register")
def register():
    data = request.get_json(silent=True) or {}
    full_name = str(data.get("full_name", "")).strip()
    email = str(data.get("email", "")).strip().lower()
    country = str(data.get("country", "")).strip()
    password = str(data.get("password", ""))
    if not full_name or len(full_name) > 120 or not country or len(country) > 80:
        return json_error("Enter your full name and country.", 400)
    if "@" not in email or len(email) > 254:
        return json_error("Enter a valid email address.", 400)
    if len(password) < 12:
        return json_error("Password must be at least 12 characters.", 400)
    try:
        if USE_POSTGRES:
            cur = execute(
                "INSERT INTO users(full_name,email,country,password_hash,created_at) VALUES(?,?,?,?,?) RETURNING id",
                (full_name, email, country, generate_password_hash(password), datetime.now(timezone.utc).isoformat())
            )
            user_id = cur.fetchone()["id"]
        else:
            cur = execute(
                "INSERT INTO users(full_name,email,country,password_hash,created_at) VALUES(?,?,?,?,?)",
                (full_name, email, country, generate_password_hash(password), datetime.now(timezone.utc).isoformat())
            )
            user_id = cur.lastrowid
        db().commit()
    except Exception as exc:
        db().rollback()
        if (USE_POSTGRES and isinstance(exc, UniqueViolation)) or (not USE_POSTGRES and isinstance(exc, sqlite3.IntegrityError)):
            return json_error("An account with that email already exists.", 409)
        app.logger.exception("Registration failed")
        return json_error("Unable to create account right now.", 500)
    session.clear()
    session["user_id"] = user_id
    session["csrf_token"] = secrets.token_urlsafe(32)
    return jsonify({"ok": True, "message": "Investor portal account created. Investment services appear when enabled for your account.", "user": {"id": user_id, "full_name": full_name, "email": email, "country": country}}), 201

@app.post("/api/login")
def login():
    data = request.get_json(silent=True) or {}
    email = str(data.get("email", "")).strip().lower()
    password = str(data.get("password", ""))
    row = execute("SELECT * FROM users WHERE email=?", (email,)).fetchone()
    if not row or not check_password_hash(row["password_hash"], password):
        return json_error("Email or password is incorrect.", 401)
    session.clear()
    session["user_id"] = row["id"]
    session["csrf_token"] = secrets.token_urlsafe(32)
    return jsonify({"ok": True, "user": {"id": row["id"], "full_name": row["full_name"], "email": row["email"], "country": row["country"], "role": row["role"]}})

@app.post("/api/logout")
@login_required
def logout():
    session.clear()
    return jsonify({"ok": True, "message": "Logged out."})

@app.get("/api/me")
@login_required
def me():
    row = execute("SELECT id,full_name,email,country,role,created_at FROM users WHERE id=?", (session["user_id"],)).fetchone()
    if not row:
        session.clear()
        return json_error("Account not found.", 404)
    return jsonify({"ok": True, "user": dict(row)})

